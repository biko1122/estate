export function getProperty(slug) {
  return properties.find((p) => p.slug === slug)
}

export function getSimilar(property, count = 3) {
  const score = (p) =>
    (p.location === property.location ? 2 : 0) +
    (p.type === property.type ? 1 : 0) +
    (p.purpose === property.purpose ? 1 : 0)
  return properties
    .filter((p) => p.id !== property.id)
    .sort((a, b) => score(b) - score(a))
    .slice(0, count)
}
